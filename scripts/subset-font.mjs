// Builds a self-hosted Noto Serif TC subset containing exactly the characters this site
// can render, and writes the @font-face that points at it.
//
// Why: Google Fonts slices a CJK family into ~120 unicode-range files. The home page's
// Chinese text lands in 20 of them — 1.7 MB, and, worse, 20 separate font-swap events,
// each one restyling and relaying out every character on the page. Lighthouse measured
// 7.5s of Style & Layout from that alone. One subset file is one swap.
//
// Run `npm run fonts` after changing any visible copy — a character that is not in the
// subset falls back to the system serif for that glyph. Deliberately NOT part of
// `npm run build`: Cloudflare Pages' git webhook is this project's only deploy trigger
// and the build command stays as small as it has always been.

import { createHash } from 'node:crypto'
import { existsSync } from 'node:fs'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import subsetFont from 'subset-font'

// Noto Serif TC, variable weight axis, already language-subset to Traditional Chinese.
const SOURCE_URL =
  'https://raw.githubusercontent.com/notofonts/noto-cjk/main/Serif/Variable/OTF/Subset/NotoSerifTC-VF.otf'
const CACHE = '.fonts-src/NotoSerifTC-VF.otf'
const OUT_DIR = 'public/fonts'
const MANIFEST = 'app/data/font.ts'

// Everything that can end up on screen lives in the components and the data modules.
// Scanning the raw file text is a superset: it also picks up code and comments, so a
// Chinese code comment quietly adds its characters to the subset and changes the output
// hash. That is deliberate. Stripping comments first would mean parsing Vue SFCs well
// enough to tell a real `//` comment from the one inside `https://…` in a template, and
// getting that wrong drops a glyph from live copy — a far worse failure than carrying a
// few unused ones.
const SCAN_ROOTS = ['app']
const SCAN_EXT = /\.(vue|ts)$/

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(path)
    else if (SCAN_EXT.test(entry.name)) yield path
  }
}

const chars = new Set()
// Baseline so the font never falls back mid-sentence on punctuation or a digit that
// happens not to appear in today's copy.
for (let c = 0x20; c <= 0x7e; c++) chars.add(String.fromCodePoint(c))
for (const c of '　、。，．・：；！？「」『』（）〔〕【】《》〈〉—…‧～￥＄％＃＠＆＊＋－＝／＼｜←→↑↓★☆♥・□■○●◎▲▼') {
  chars.add(c)
}

let files = 0
for (const root of SCAN_ROOTS) {
  for await (const file of walk(root)) {
    files++
    for (const ch of await readFile(file, 'utf8')) chars.add(ch)
  }
}
// The one file outside app/ that carries visible copy (the title template lives there).
for (const ch of await readFile('nuxt.config.ts', 'utf8')) chars.add(ch)

const text = [...chars].join('')
const cjk = [...chars].filter((c) => /\p{Script=Han}/u.test(c)).length

if (!existsSync(CACHE)) {
  console.log(`fetching ${SOURCE_URL}`)
  await mkdir('.fonts-src', { recursive: true })
  const res = await fetch(SOURCE_URL)
  if (!res.ok) throw new Error(`font download failed: ${res.status}`)
  await writeFile(CACHE, Buffer.from(await res.arrayBuffer()))
}

const source = await readFile(CACHE)
const subset = await subsetFont(source, text, {
  targetFormat: 'woff2',
  // Keep the weight axis: the design draws hierarchy from 500 / 700 / 900 of one family.
  variationAxes: { wght: { min: 400, max: 900 } },
})

const hash = createHash('sha256').update(subset).digest('hex').slice(0, 8)
const name = `noto-serif-tc-${hash}.woff2`

await rm(OUT_DIR, { recursive: true, force: true })
await mkdir(OUT_DIR, { recursive: true })
await writeFile(join(OUT_DIR, name), subset)

const url = `/fonts/${name}`
const face = `@font-face{font-family:'Noto Serif TC';font-style:normal;font-weight:400 900;font-display:swap;src:url('${url}') format('woff2')}`

await writeFile(
  MANIFEST,
  `// GENERATED by scripts/subset-font.mjs — do not edit by hand.
// Run \`npm run fonts\` after changing visible copy, so new characters get into the subset.

export const FONT_URL = ${JSON.stringify(url)}

/** Inlined into <head>, so the face is declared without costing a stylesheet round trip. */
export const FONT_FACE_CSS = ${JSON.stringify(face)}
`,
  'utf8',
)

const kb = (n) => `${(n / 1024).toFixed(0)} KB`
console.log(`scanned ${files} files -> ${chars.size} characters (${cjk} Han)`)
console.log(`${CACHE} ${kb(source.length)} -> ${OUT_DIR}/${name} ${kb(subset.length)}`)
console.log(`manifest written to ${MANIFEST}`)
