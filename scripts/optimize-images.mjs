// Pre-generates responsive AVIF/WebP variants for every photo in public/images.
//
// Run manually (`npm run images`) and commit the output — deliberately NOT wired into
// `npm run build`. Cloudflare Pages' git webhook is the only deploy trigger this project
// has, so the build command stays exactly what it was; a sharp install failing on the
// build runner would take the live site's deployments down with it.
//
// The originals stay untouched as the <img src> fallback. Every browser that matters
// picks a <source>, so the full-size JPEG is never actually fetched.

import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { basename, extname, join } from 'node:path'
import sharp from 'sharp'

const SRC_DIR = 'public/images'
const OUT_DIR = 'public/images/opt'
const MANIFEST = 'app/data/image-manifest.ts'

// The hero is the only full-bleed image, so it is the only one that needs widths past a
// column. Everything else tops out in a ~512px slot; 960 covers that at 2x DPR.
const HERO_WIDTHS = [640, 768, 960, 1280, 1920]
const CONTENT_WIDTHS = [320, 480, 640, 960]
const HERO = new Set(['hero-bg'])

// og.jpg is the social share card. Scrapers want one plain JPEG at a fixed size, and no
// <picture> ever points at it, so variants would be dead weight.
const SKIP = new Set(['og'])

const avif = { quality: 50, effort: 4 }
const webp = { quality: 78, effort: 4 }

const files = (await readdir(SRC_DIR, { withFileTypes: true }))
  .filter((e) => e.isFile() && /\.jpe?g$/i.test(e.name))
  .map((e) => e.name)
  .sort()

// Wipe and rebuild: variant filenames carry a content hash, so stale runs would otherwise
// leave orphans behind that nothing references and nobody notices.
await rm(OUT_DIR, { recursive: true, force: true })
await mkdir(OUT_DIR, { recursive: true })

const manifest = {}
let srcBytes = 0
let outBytes = 0

for (const file of files) {
  const base = basename(file, extname(file))
  if (SKIP.has(base)) continue

  const input = join(SRC_DIR, file)
  const image = sharp(input)
  const { width, height } = await image.metadata()
  if (!width || !height) throw new Error(`no dimensions for ${file}`)

  // Never upscale: a variant wider than the source would be bigger with no more detail.
  const ladder = (HERO.has(base) ? HERO_WIDTHS : CONTENT_WIDTHS).filter((w) => w < width)

  // Several source photos are narrower than the top rung (443px dish shots, 590px award).
  // Without a rung at their own width the modern formats would be capped below what the
  // JPEG already delivers, so a 2x screen would render them softer than it does today.
  // Skipped past 1280 (the hero) and when the gap is under 15%, where it buys nothing.
  const top = ladder[ladder.length - 1] ?? 0
  const widths =
    width <= 1280 && width > top * 1.15 ? [...ladder, width] : ladder.length ? ladder : [width]

  // Hash the source, not each output: every variant of a photo then shares one token, and
  // replacing the photo renames all of them at once. That is what lets `_headers` serve
  // public/images/opt as immutable for a year without ever pinning a stale picture.
  const hash = createHash('sha256').update(await readFile(input)).digest('hex').slice(0, 8)

  const emitted = []
  for (const w of widths) {
    const resized = image.clone().resize({ width: w, withoutEnlargement: true })
    for (const [ext, opts] of [
      ['avif', avif],
      ['webp', webp],
    ]) {
      const out = join(OUT_DIR, `${base}-${w}.${hash}.${ext}`)
      const { size } = await resized.clone()[ext](opts).toFile(out)
      outBytes += size
    }
    emitted.push(w)
  }

  srcBytes += (await stat(input)).size

  manifest[base] = { w: width, h: height, hash, widths: emitted }
  console.log(`${base}  ${width}x${height}  ->  ${emitted.join(', ')}`)
}

const body = `// GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Run \`npm run images\` after adding or replacing a photo in public/images.

export interface ImageMeta {
  /** Intrinsic width of the original, for the <img> width attribute (CLS). */
  w: number
  /** Intrinsic height of the original. */
  h: number
  /** Content hash of the source, embedded in every variant filename. */
  hash: string
  /** Variant widths that exist under public/images/opt, ascending. */
  widths: number[]
}

export const IMAGE_MANIFEST: Record<string, ImageMeta> = ${JSON.stringify(manifest, null, 2)}
`

await writeFile(MANIFEST, body, 'utf8')

const mb = (n) => `${(n / 1024 / 1024).toFixed(2)} MB`
console.log(`\n${Object.keys(manifest).length} photos`)
console.log(`originals ${mb(srcBytes)} -> variants ${mb(outBytes)} (all widths, both formats)`)
console.log(`manifest written to ${MANIFEST}`)
